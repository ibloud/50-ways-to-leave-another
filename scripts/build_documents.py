#!/usr/bin/env python3
"""Build committed static reading pages without changing Markdown source content."""
import argparse
import html
import os
from pathlib import Path
import re
import sys
from html.parser import HTMLParser
from urllib.parse import unquote, urlsplit
import markdown

ROOT = Path(__file__).resolve().parents[1]
MARKER = '<!-- Generated by scripts/build_documents.py; edit the Markdown source. -->'


def sources():
    return sorted(p for p in ROOT.rglob('*.md') if '.git' not in p.parts and p.name != 'AGENTS.md')


def web_links(text, parent):
    def replace(match):
        url = html.unescape(match.group(2))
        split = urlsplit(url)
        if split.scheme or split.netloc or not split.path.endswith('.md'):
            return match.group(0)
        target = ROOT / split.path.lstrip('/') if split.path.startswith('/') else parent / unquote(split.path)
        if not target.is_file() or target.name == 'AGENTS.md':
            return match.group(0)
        converted = split.path[:-3] + '.html'
        if split.query:
            converted += '?' + split.query
        if split.fragment:
            converted += '#' + split.fragment
        return match.group(1) + html.escape(converted, quote=True) + match.group(3)
    return re.sub(r'(\bhref=[\"\x27])([^\"\x27]+)([\"\x27])', replace, text)


def render(path):
    source = path.read_text()
    engine = markdown.Markdown(extensions=['tables', 'fenced_code', 'toc', 'sane_lists'])
    body = web_links(engine.convert(source), path.parent)
    body = body.replace('<table>', '<div class="table-scroll" role="region" aria-label="Scrollable data table" tabindex="0"><table>').replace('</table>', '</table></div>')
    body = re.sub(r'style="text-align: (right|center);"', r'class="align-\1"', body)
    title_match = re.search(r'^#\s+(.+)$', source, re.M)
    title = title_match.group(1) if title_match else path.stem
    title = re.sub(r'[*`]', '', title)
    prefix = os.path.relpath(ROOT, path.parent).replace(os.sep, '/') + '/'
    esc = html.escape
    # Preserve the excluded PIXIE module's existing document wrapper.
    pixie_document = path.relative_to(ROOT).parts[0] == 'pixie'
    styles = f'<link rel="stylesheet" href="{prefix}assets/site.css">'
    navigation = f'<a href="{prefix}START-HERE.html">Learning path</a><a href="{prefix}index.html#documents">Documents</a>'
    breadcrumbs = ''
    if pixie_document:
        styles += f'\n<link rel="stylesheet" href="{prefix}assets/documents.css">'
    else:
        navigation = ''.join(
            f'<a href="{prefix}{target}"' + (' aria-current="page"' if path.relative_to(ROOT).with_suffix('.html').as_posix() == target else '') + f'>{label}</a>'
            for target, label in [('START-HERE.html', 'Start here'), ('CURRICULUM.html', 'Modules'), ('exercises/fictional-capstone.html', 'Practice'), ('ASSESSMENT-RUBRIC.html', 'Check your work')]
        ) + f'<a href="{prefix}index.html#documents">Documents</a>'
        breadcrumbs = f'<nav class="document-breadcrumbs" aria-label="Breadcrumb"><a href="{prefix}index.html">50 Ways</a><span aria-hidden="true">/</span><a href="{prefix}START-HERE.html">Learning path</a><span aria-hidden="true">/</span><span aria-current="page">{esc(title)}</span></nav>'
    source_download = '' if pixie_document else ' download'
    source_label = 'View Markdown source' if pixie_document else 'Download Markdown source'
    return f'''<!DOCTYPE html>
{MARKER}
<html lang="en">
<head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)} | 50 Ways to Leave Another</title>
{styles}
<link rel="icon" href="{prefix}assets/favicon.svg" type="image/svg+xml">
</head>
<body>
<a class="skip" href="#main">Skip to main content</a>
<header class="site-header document-header">
<a class="wordmark" href="{prefix}index.html"><span class="number" aria-hidden="true">50</span><span>Ways to Leave Another</span></a>
<nav aria-label="Document navigation">{navigation}</nav>
</header>
<main id="main" class="document-page">{breadcrumbs}<article>
{body}
<p class="document-source"><a data-source-link="true" href="{esc(path.name, quote=True)}"{source_download}>{source_label}</a> · Presentation does not indicate legal review or clearance. See the document's stated status.</p>
</article></main>
<footer><span><a href="{prefix}privacy.html">Privacy</a> · <a href="{prefix}terms.html">Terms</a> · <a href="{prefix}AI-DISCLOSURE.html">AI disclosure</a></span><span>&copy; 2026 Dominique Devereaux / Loptr Lab</span><span>Open development record · Not legal advice</span></footer>
</body></html>
'''


class Page(HTMLParser):
    def __init__(self, text):
        super().__init__(convert_charrefs=True)
        self.ids = set()
        self.duplicates = []
        self.links = []
        self.feed(text)

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if 'id' in a:
            if a['id'] in self.ids:
                self.duplicates.append(a['id'])
            self.ids.add(a['id'])
        for attribute in ('href', 'src'):
            if attribute in a:
                self.links.append((a[attribute], 'data-source-link' in a))


def validate():
    pages = {p: Page(p.read_text()) for p in ROOT.rglob('*.html') if '.git' not in p.parts}
    errors = []
    for path, page in pages.items():
        for duplicate in page.duplicates:
            errors.append(f'{path.relative_to(ROOT)}: duplicate id {duplicate}')
        for target, source_link in page.links:
            split = urlsplit(target)
            if split.scheme or split.netloc:
                continue
            dest = (ROOT / unquote(split.path).lstrip('/') if split.path.startswith('/') else path.parent / unquote(split.path)).resolve() if split.path else path
            if dest.is_dir():
                dest /= 'index.html'
            if not dest.exists():
                errors.append(f'{path.relative_to(ROOT)}: missing {target}')
            elif split.fragment and dest in pages and unquote(split.fragment) not in pages[dest].ids:
                errors.append(f'{path.relative_to(ROOT)}: missing fragment {target}')
            if split.path.endswith('.md') and not source_link:
                errors.append(f'{path.relative_to(ROOT)}: reading link still points to Markdown: {target}')
    return errors, len(pages)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    errors = []
    generated = 0
    for path in sources():
        dest = path.with_suffix('.html')
        # Preserve bespoke pages and their existing layout.
        if dest.exists() and MARKER not in dest.read_text():
            continue
        expected = render(path)
        if args.check:
            if not dest.exists() or dest.read_text() != expected:
                errors.append(f'Stale generated page: {dest.relative_to(ROOT)}')
        else:
            dest.write_text(expected)
        generated += 1
    if not args.check:
        for path in ROOT.rglob('*.html'):
            if '.git' in path.parts or MARKER in path.read_text():
                continue
            old = path.read_text()
            # Explicit source/download links stay Markdown; reading links become HTML.
            saved = []
            def protect(match):
                saved.append(match.group(0))
                return f'__SOURCE_LINK_{len(saved)-1}__'
            protected = re.sub(r'<a\b[^>]*data-source-link[^>]*>.*?</a>', protect, old, flags=re.S)
            updated = web_links(protected, path.parent)
            for i, link in enumerate(saved):
                updated = updated.replace(f'__SOURCE_LINK_{i}__', link)
            if old != updated:
                path.write_text(updated)
    link_errors, count = validate()
    errors += link_errors
    if errors:
        print('\n'.join(errors))
        return 1
    print(f'PASS: {generated} generated documents; {count} HTML pages checked for local links, fragments and Markdown reading links.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
